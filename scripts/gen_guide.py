PAGES = {"faults.md": faults_page, "scenarios.md": scenarios_page, "messages.md": messages_page, "settings.md": settings_page}


def build() -> dict[str, str]:
    missing = [m for m in sorted(set(Station.CP_ACTIONS) | CP_ACTIONS_16) if m not in STATION_MESSAGES]
    missing += [f"command {m}" for m in COMMAND_NAMES if m not in COMMANDS_201]
    missing += [f"1.6 command {m}" for m in COMMAND_NAMES_16 if m not in COMMANDS_16]
    if missing:
        raise SystemExit("scripts/gen_guide.py has no description for: " + ", ".join(missing))
    return {name: fn() for name, fn in PAGES.items()}


def main() -> int:
    pages = build()
    if "--check" in sys.argv:
        stale = [n for n, text in pages.items() if not (OUT / n).exists() or (OUT / n).read_text() != text]
        if stale:
            print("out of date:", ", ".join(stale), "\nrun: backend/.venv/bin/python scripts/gen_guide.py")
            return 1
        print("guide reference pages are up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (OUT / name).write_text(text)
        print("wrote", (OUT / name).relative_to(ROOT), f"({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
