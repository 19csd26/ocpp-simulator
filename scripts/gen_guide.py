def md_table(header: list[str], rows: list[list[str]]) -> str:
    esc = lambda c: str(c).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|", *["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]])


# ---------------------------------------------------------------------------------------------------- faults
def allowed(p: dict) -> str:
    if p.get("options"):
        return "one of " + ", ".join(f"`{o}`" for o in p["options"])
    lo, hi = p.get("min"), p.get("max")
    if lo is not None and hi is not None:
        return f"{lo} to {hi}"
    if lo is not None:
        return f"{lo} or more"
    if hi is not None:
        return f"up to {hi}"
    return ""


def anchor(group: str) -> str:
    return group.lower().replace(" & ", "--").replace(" ", "-")


def faults_page() -> str:
    blocks = [HEADER.strip(), "# Fault reference",
              "Every fault Volkai can inject, generated from the code. How to use faults, with diagrams and examples: [Faults and injection](../04-faults-and-injection.md)."]
    groups: dict[str, list[str]] = {}
    for kind, spec in FAULTS.items():
        groups.setdefault(spec.get("group", "Other"), []).append(kind)
    blocks.append(f"**{len(FAULTS)} faults.** " + " · ".join(f"[{g}](#{anchor(g)})" for g in groups))
    for group, kinds in groups.items():
        blocks.append(f"## {group}")
        for kind in kinds:
            spec = FAULTS[kind]
            scope = {"station": "the whole station", "evse": "one EVSE", "both": "one EVSE or the whole station"}[spec["scope"]]
            lasts = "a one-time event (nothing to clear)" if spec.get("oneshot") else "until cleared, or for the number of seconds you set (`duration_s`)"
            blocks.append(f"### `{kind}`: {spec['title']}")
            blocks.append(f"- **Applies to:** {scope}\n- **Lasts:** {lasts}")
            blocks.append(f"**What it does.** {spec['description']}")
            blocks.append(f"**What your CSMS should do.** {spec['expect']}")
            if spec["params"]:
                blocks.append(md_table(["Parameter", "Meaning", "Default", "Allowed"], [[f"`{p['key']}`", p["label"], f"`{json.dumps(p['default'])}`", allowed(p)] for p in spec["params"]]))
            else:
                blocks.append("No parameters.")
            example = {"kind": kind, **({"scope": 1} if spec["scope"] != "station" else {}), **({"params": {p["key"]: p["default"] for p in spec["params"][:1]}} if spec["params"] else {})}
            blocks.append(f"API: `POST /api/stations/{{id}}/faults` with body `{json.dumps(example)}`.")
    return "\n\n".join(blocks) + FOOTER


# ------------------------------------------------------------------------------------------------- scenarios
def step_text(step: dict) -> str:
    if step.get("label"):
        return step["label"]
    return describe(step)


def scenarios_page() -> str:
    blocks = [HEADER.strip(), "# Scenario reference",
              "Every built-in test case, generated from the code. How scenarios work and how to write your own: [Scenarios](../06-scenarios.md).",
              "A step marked **1.6** is replaced on an OCPP 1.6 charger, and a step marked **only 2.0.1** / **only 1.6** is skipped on the other version. "
              "`$card` and `$card2` stand for the cards set on the charger."]
    groups: dict[str, list[dict]] = {}
    for sc in CATALOG_SCENARIOS.values():
        groups.setdefault(sc["group"], []).append(sc)
    blocks.append(f"**{len(CATALOG_SCENARIOS)} scenarios.** " + " · ".join(f"[{g}](#{anchor(g)})" for g in groups))
    for group, scs in groups.items():
        blocks.append(f"## {group}")
        for sc in scs:
            blocks.append(f"### `{sc['id']}`: {sc['title']}")
            blocks.append(sc["description"])
            rows = []
            for i, step in enumerate(sc["steps"], 1):
                kind = ("do " + step["do"]) if "do" in step else ("expect " + step["expect"])
                notes = []
                if step.get("only"):
                    notes.append(f"only {step['only']}")
                if step.get("v16"):
                    notes.append("1.6: " + (step["v16"].get("label") or describe({k: v for k, v in {**step, **step["v16"]}.items() if k not in ("v16", "only") and v is not None})))
                if step.get("timeout"):
                    notes.append(f"waits up to {step['timeout']:g} s")
                if step.get("continue_on_fail"):
                    notes.append("continues even if it fails")
                rows.append([i, f"`{kind}`", step_text({k: v for k, v in step.items() if k not in ("v16", "only")}), "; ".join(notes)])
            blocks.append(md_table(["#", "Step", "Detail", "Notes"], rows))
    blocks.append("## Step vocabulary")
    blocks.append("**`do` actions:** " + ", ".join(f"`{a}`" for a in sorted(Runner.ACTIONS)) + ".")
    blocks.append("**`expect` checks:** " + ", ".join(f"`{e}`" for e in sorted(Runner.EXPECTS)) + ".")
    return "\n\n".join(blocks) + FOOTER


